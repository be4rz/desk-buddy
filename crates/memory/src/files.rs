//! The generated `MEMORY.md`, and erasing everything.

use crate::{Error, Result, Store};
use std::fs;
use std::io::ErrorKind;
use std::path::Path;

pub(crate) const DB: &str = "memory.sqlite";
pub(crate) const HEADER: &str = "<!-- Generated by desk-buddy from memory.sqlite. Edit in the What I remember window; changes here are overwritten. -->";
const EMPTY: &str = "Nothing yet. The bear hasn't noted anything lasting about you.";

impl Store {
    /// Rewrites `MEMORY.md` from the live rows (atomically: a temp file, then a rename) and the
    /// `notes/` files of the days with episodes or insights.
    pub fn write_files(&self) -> Result<()> {
        if self.is_newer() {
            return Err(Error::Newer);
        }
        let section = self.section();
        let body = if section.is_empty() { EMPTY } else { section.as_str() };
        let path = self.dir().join("MEMORY.md");
        let tmp = self.dir().join("MEMORY.md.tmp");
        fs::write(&tmp, format!("{HEADER}\n\n{body}\n"))?;
        fs::rename(&tmp, path)?;
        self.write_notes()
    }

    /// Deletes the store, its WAL files and the generated files, then opens a fresh one and vacuums it.
    /// It never opens the old file, so it recovers a corrupt or newer one too. Drop the old `Store` first.
    pub fn forget_all(dir: &Path) -> Result<Store> {
        for name in [DB, "memory.sqlite-wal", "memory.sqlite-shm", "memory.sqlite-journal", "MEMORY.md", "MEMORY.md.tmp"] {
            ignore_missing(fs::remove_file(dir.join(name)))?;
        }
        ignore_missing(fs::remove_dir_all(dir.join("notes")))?;
        let store = Store::open(dir)?;
        store.vacuum()?;
        Ok(store)
    }
}

fn ignore_missing(r: std::io::Result<()>) -> Result<()> {
    match r {
        Err(e) if e.kind() != ErrorKind::NotFound => Err(e.into()),
        _ => Ok(()),
    }
}
