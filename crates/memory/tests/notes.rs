//! `notes/YYYY-MM-DD.md`, and what forgetting or erasing does to the notes, the insight links and the search index.
mod common;
use common::*;
use serde_json::json;
use std::fs;
use std::path::PathBuf;

const HEADER: &str = "<!-- Generated by desk-buddy from memory.sqlite. Edit in the What I remember window; changes here are overwritten. -->";

fn note(t: &Tmp, day: &str) -> PathBuf {
    t.mem().join("notes").join(format!("{day}.md"))
}

fn names(t: &Tmp) -> Vec<String> {
    let mut v: Vec<String> = match fs::read_dir(t.mem().join("notes")) {
        Ok(d) => d.map(|e| e.unwrap().file_name().to_string_lossy().into_owned()).collect(),
        Err(_) => vec![],
    };
    v.sort();
    v
}

/// Two days of episodes and one insight over them.
fn fixture() -> (Tmp, memory::Store, Vec<i64>, i64) {
    let (t, s) = store();
    for i in 0..10 {
        s.add("preference", &format!("Likes tea number {i}"), &now_on(date(2026, 11, 1))).unwrap(); // keeps one insight under the guard
    }
    let e = vec![
        episode(&s, date(2026, 11, 25), "Mochi the cat knocked over the tea", 6),
        episode(&s, date(2026, 11, 25), "Planned the Lanternfish Labs offsite", 5),
        episode(&s, date(2026, 11, 26), "Lan came by to fix the router", 5),
    ];
    let j = s.reflect_args(date(2026, 11, 27), &now()).unwrap();
    s.apply_reflect(&j, &json!({"insights": [{"text": "Mochi keeps making a mess", "importance": 6, "sources": [e[0], e[2]]}]}), &now()).unwrap();
    s.write_files().unwrap();
    let insight: i64 = db(&t.mem()).query_row("SELECT id FROM facts WHERE kind = 'insight'", [], |r| r.get(0)).unwrap();
    (t, s, e, insight)
}

#[test]
fn a_note_has_the_exact_header_a_dated_title_and_one_line_per_item() {
    let (t, _s, _e, _i) = fixture();
    assert_eq!(names(&t), ["2026-11-25.md", "2026-11-26.md", "2026-11-27.md"]);
    assert_eq!(
        fs::read_to_string(note(&t, "2026-11-25")).unwrap(),
        format!("{HEADER}\n\n# Wed 25 Nov 2026\n\n- Mochi the cat knocked over the tea\n- Planned the Lanternfish Labs offsite\n")
    );
    assert_eq!(
        fs::read_to_string(note(&t, "2026-11-26")).unwrap(),
        format!("{HEADER}\n\n# Thu 26 Nov 2026\n\n- Lan came by to fix the router\n")
    );
    // the insight was observed today: its note says what it is and how many moments back it
    assert_eq!(
        fs::read_to_string(note(&t, "2026-11-27")).unwrap(),
        format!("{HEADER}\n\n# Fri 27 Nov 2026\n\n- Pattern: Mochi keeps making a mess (from 2 moments)\n")
    );
}

#[test]
fn an_insight_with_one_source_says_moment_in_the_singular() {
    let (t, s, e, _i) = fixture();
    let j2e = episode(&s, date(2026, 11, 27), "Another small thing happened", 5);
    let j = s.reflect_args(date(2026, 11, 27), &now()).unwrap();
    s.apply_reflect(&j, &json!({"insights": [{"text": "A lone pattern", "sources": [j2e]}]}), &now()).unwrap();
    s.write_files().unwrap();
    let text = fs::read_to_string(note(&t, "2026-11-27")).unwrap();
    assert!(text.contains("- Pattern: A lone pattern (from 1 moment)\n"), "{text}");
    let _ = e;
}

#[test]
fn a_file_is_written_only_when_it_changed() {
    let (t, s, _e, _i) = fixture();
    let p = note(&t, "2026-11-25");
    // a marker in the file's mtime-independent form: replace it by an older copy of itself
    let old = std::time::SystemTime::UNIX_EPOCH + std::time::Duration::from_secs(1_000_000);
    fs::File::options().write(true).open(&p).unwrap().set_modified(old).unwrap();
    s.write_files().unwrap();
    assert_eq!(fs::metadata(&p).unwrap().modified().unwrap(), old, "unchanged content: not rewritten");
    // a changed day is rewritten, the others are not
    fs::File::options().write(true).open(note(&t, "2026-11-26")).unwrap().set_modified(old).unwrap();
    episode(&s, date(2026, 11, 25), "A third thing on the same day", 5);
    s.write_files().unwrap();
    assert_eq!(fs::metadata(&p).unwrap().modified().unwrap(), old.max(fs::metadata(&p).unwrap().modified().unwrap()));
    assert!(fs::read_to_string(&p).unwrap().contains("A third thing on the same day"));
    assert_eq!(fs::metadata(note(&t, "2026-11-26")).unwrap().modified().unwrap(), old);
    assert!(!t.mem().join("notes").join("2026-11-25.md.tmp").exists());
}

#[test]
fn a_temp_note_left_by_a_crash_is_swept() {
    let (t, s, e, _i) = fixture();
    let stray = t.mem().join("notes").join("2026-11-25.md.tmp");
    fs::write(&stray, "a moment the person later forgot").unwrap();
    s.soft_forget(e[0]).unwrap();
    assert!(!stray.exists(), "the half-written copy goes too");
}

#[test]
fn a_day_with_nothing_live_loses_its_note_and_strangers_are_left_alone() {
    let (t, s, e, _i) = fixture();
    fs::write(t.mem().join("notes").join("README.txt"), "mine").unwrap();
    fs::write(t.mem().join("notes").join("2026-1-1.md"), "mine too").unwrap();
    s.soft_forget(e[2]).unwrap();
    assert_eq!(names(&t), ["2026-1-1.md", "2026-11-25.md", "2026-11-27.md", "README.txt"]);
    s.soft_forget(e[0]).unwrap();
    s.soft_forget(e[1]).unwrap();
    assert_eq!(names(&t), ["2026-1-1.md", "2026-11-27.md", "README.txt"], "the insight keeps its day");
}

#[test]
fn forgetting_a_row_by_id_or_key_rerenders_the_notes_at_once() {
    let (t, s, e, _i) = fixture();
    s.forget(Some(e[1]), None, None).unwrap();
    let text = fs::read_to_string(note(&t, "2026-11-25")).unwrap();
    assert!(!text.contains("offsite") && text.contains("Mochi the cat"), "{text}");
}

#[test]
fn erasing_an_episode_removes_its_words_from_the_notes_the_index_and_the_file() {
    let (t, s, e, _i) = fixture();
    s.erase(e[2]).unwrap();
    assert_eq!(names(&t), ["2026-11-25.md", "2026-11-27.md"]);
    assert!(s.search("router", 10).unwrap().is_empty());
    assert_eq!(count(&t.mem(), "SELECT count(*) FROM facts_fts WHERE facts_fts MATCH 'router'"), 0);
    db(&t.mem()).execute("INSERT INTO facts_fts(facts_fts, rank) VALUES ('integrity-check', 1)", []).unwrap();
    let bytes = fs::read(t.mem().join("memory.sqlite")).unwrap();
    assert!(!bytes.windows(6).any(|w| w == b"router"), "the bytes are gone from the file");
    // it no longer backs the insight
    assert_eq!(count(&t.mem(), &format!("SELECT count(*) FROM insight_sources WHERE episode_id = {}", e[2])), 0);
}

#[test]
fn erasing_an_insight_takes_its_links_and_note_line_with_it() {
    let (t, s, _e, i) = fixture();
    s.erase(i).unwrap();
    assert_eq!(count(&t.mem(), "SELECT count(*) FROM insight_sources"), 0);
    assert_eq!(names(&t), ["2026-11-25.md", "2026-11-26.md"]);
    assert!(s.search("mess", 10).unwrap().is_empty());
}

#[test]
fn a_soft_forgotten_episode_stops_backing_the_insight_which_stays() {
    let (t, s, e, i) = fixture();
    s.soft_forget(e[0]).unwrap();
    assert_eq!(row(&t.mem(), i).0, "live");
    assert_eq!(count(&t.mem(), "SELECT count(*) FROM insight_sources"), 1);
    assert_eq!(count(&t.mem(), &format!("SELECT count(*) FROM insight_sources WHERE episode_id = {}", e[0])), 0);
    // the forgotten text is out of search and out of the note
    assert!(s.search("knocked", 10).unwrap().is_empty());
    assert!(!fs::read_to_string(note(&t, "2026-11-25")).unwrap().contains("knocked"));
    assert!(fs::read_to_string(note(&t, "2026-11-27")).unwrap().contains("(from 1 moment)"));
}

#[test]
fn notes_are_not_created_by_forgetting_alone() {
    let (t, s) = store();
    let e = episode(&s, date(2026, 11, 25), "Something small", 5);
    s.soft_forget(e).unwrap();
    assert!(!t.mem().join("notes").exists(), "only write_files makes notes/");
    s.write_files().unwrap();
    assert!(!t.mem().join("notes").exists(), "and an empty one is not made");
    assert!(t.mem().join("MEMORY.md").exists());
}

#[test]
fn forget_all_removes_the_notes_folder() {
    let (t, s, _e, _i) = fixture();
    fs::write(t.mem().join("notes").join("README.txt"), "mine").unwrap();
    drop(s);
    let s = memory::Store::forget_all(&t.mem()).unwrap();
    assert!(!t.mem().join("notes").exists());
    assert_eq!(count(&t.mem(), "SELECT count(*) FROM facts"), 0);
    assert!(s.search("Mochi", 10).unwrap().is_empty());
}
